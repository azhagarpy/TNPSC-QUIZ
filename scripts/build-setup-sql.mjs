// Concatenates every migration (in order) plus the sample questions into
// supabase/setup.sql, for a one-time paste into Supabase → SQL Editor on a
// fresh project. (With the Supabase CLI, use `supabase db push` instead.)
//
//   npm run setup-sql
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1');
const dir = join(root, 'supabase', 'migrations');
const parts = readdirSync(dir)
  .filter((f) => f.endsWith('.sql'))
  .sort()
  .map((f) => `-- ==== ${f} ====\n${readFileSync(join(dir, f), 'utf8')}`);
parts.push(`-- ==== seed.sql (sample questions) ====\n${readFileSync(join(root, 'supabase', 'seed.sql'), 'utf8')}`);

writeFileSync(
  join(root, 'supabase', 'setup.sql'),
  `-- Generated by scripts/build-setup-sql.mjs. Run once on a fresh project.\n\n${parts.join('\n\n')}`,
);
console.log(`Wrote supabase/setup.sql (${parts.length} parts)`);
